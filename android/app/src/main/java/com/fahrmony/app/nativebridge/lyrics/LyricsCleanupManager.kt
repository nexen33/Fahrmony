/**
 * 歌词噪声文本清洗与纯音乐智能识别引擎
 */
object LyricsCleanupManager {

    // 头部元数据标签正则: [ti:xxx], [ar:xxx], [al:xxx], [by:xxx], [offset:xxx], [re:xxx], [ve:xxx]
    private val HEADER_TAG_PATTERN = Pattern.compile("^\\[(ti|ar|al|by|offset|re|ve|length):[^\\]]*\\]", Pattern.CASE_INSENSITIVE)

    // 制作人员/噪声非演唱行前缀规则
    private val NOISE_PREFIXES = arrayOf(
        "作词", "作詞", "作 词", "作 詞", "词", "詞",
        "作曲", "作 曲", "曲",
        "编曲", "編曲", "编 曲", "編曲",
        "制作人", "製作人", "制作", "製作", "监制", "監製",
        "混音", "录音", "錄音", "母带", "母帶",
        "吉他", "贝斯", "键盘", "鼓", "弦乐", "和声", "伴唱",
        "Written by", "Composed by", "Arranged by", "Produced by",
        "Mixed by", "Mastered by", "Recorded by", "Vocals by",
        "Lyricist", "Composer", "Producer"
    )

    // 纯音乐/无填词标记关键字
    private val PURE_MUSIC_KEYWORDS = arrayOf(
        "纯音乐，请欣赏",
        "純音樂，請欣賞",
        "纯音乐",
        "純音樂",
        "没有填词的纯音乐",
        "没有填词",
        "此歌曲为没有填词的纯音乐",
        "纯音乐 (请欣赏)",
        "Instrumental",
        "No lyrics available"
    )

    /**
     * 判断是否为 LRC 头部元数据标签
     */
    fun isHeaderTag(line: String): Boolean {
        return HEADER_TAG_PATTERN.matcher(line.trim()).find()
    }

    /**
     * 判断是否为纯音乐/无填词声明文本
     */
    fun isPureMusicDeclaration(text: String): Boolean {
        val clean = text.trim()
        if (clean.isBlank()) return false
        return PURE_MUSIC_KEYWORDS.any { clean.contains(it, ignoreCase = true) }
    }

    /**
     * 判断单行歌词是否属于作词/作曲/制作人等非演唱噪声行
     */
    fun isNoiseLine(text: String): Boolean {
        val clean = text.trim()
        if (clean.isBlank()) return true

        // 包含纯音乐标记直接属于特殊行
        if (isPureMusicDeclaration(clean)) return true

        for (prefix in NOISE_PREFIXES) {
            // 匹配格式: "作词: xxx", "作词：xxx", "作词 / xxx", "Written by: xxx"
            if (clean.startsWith(prefix, ignoreCase = true)) {
                val remainder = clean.substring(prefix.length).trim()
                if (remainder.isEmpty() || remainder.startsWith(":") || remainder.startsWith("：") || 
                    remainder.startsWith("/") || remainder.startsWith("-") || remainder.startsWith(" ")) {
                    return true
                }
            }
        }
        return false
    }

