    private val TRAD_CHARS: CharArray
    private val SIMP_CHARS: CharArray

    init {
        val pairs = ArrayList<Pair<Char, Char>>(RAW_TRAD_SIMP_PAIRS.length / 2)
        var i = 0
        while (i < RAW_TRAD_SIMP_PAIRS.length - 1) {
            val trad = RAW_TRAD_SIMP_PAIRS[i]
            val simp = RAW_TRAD_SIMP_PAIRS[i + 1]
            // 严格排除繁简同字与非法空白
            if (trad != simp && trad > ' ' && simp > ' ') {
                pairs.add(Pair(trad, simp))
            }
            i += 2
        }
        // 按繁体字符 Unicode 严格排序并去重，保证 binarySearch 二分查找单调性
        val sortedDistinct = pairs.distinctBy { it.first }.sortedBy { it.first }
        TRAD_CHARS = CharArray(sortedDistinct.size)
        SIMP_CHARS = CharArray(sortedDistinct.size)
        for (idx in sortedDistinct.indices) {
            TRAD_CHARS[idx] = sortedDistinct[idx].first
            SIMP_CHARS[idx] = sortedDistinct[idx].second
        }
    }

    /**
     * 将繁体中文自动规范化转换为简体中文 (基于有序字符数组的 0-GC 二分查找)
     */
    fun toSimplifiedChinese(text: String): String {
        if (text.isEmpty()) return text
        var modified = false
        val chars = text.toCharArray()
        for (i in chars.indices) {
            val idx = Arrays.binarySearch(TRAD_CHARS, chars[i])
            if (idx >= 0) {
                chars[i] = SIMP_CHARS[idx]
                modified = true
            }
        }
        return if (modified) String(chars) else text
    }

    // 多余连续空白正则预编译，消除逐行清洗动态编译开销
    private val MULTI_SPACE_REGEX = Regex("\\s+")

    /**
     * 清洗歌词文本中的多余空白、异常字符并根据配置自动转换为简体中文
     */
    fun cleanText(text: String, convertToSimplified: Boolean = true): String {
        val trimmed = text.trim().replace(MULTI_SPACE_REGEX, " ")
        return if (convertToSimplified) toSimplifiedChinese(trimmed) else trimmed
    }
